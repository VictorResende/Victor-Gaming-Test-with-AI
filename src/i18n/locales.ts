export type I18nKey = keyof typeof translations.pt;

let currentLang: Language = 'pt';

export function setLanguage(lang: Language) {
  currentLang = lang;
}

export function getLanguage(): Language {
  return currentLang;
}

export function t(key: keyof typeof translations.pt, params?: Record<string, string | number>): string {
  let str: string = (translations[currentLang] && translations[currentLang][key]) || translations.pt[key] || (key as string);
  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
    }
  }
  return str;
}
